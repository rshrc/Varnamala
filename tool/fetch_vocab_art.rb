# frozen_string_literal: true

# Downloads one flat SVG per concept in assets/courses/concepts.json into
# assets/images/vocab/, so the First words course can show a picture instead of
# an English translation.
#
# The art comes from Twemoji rather than being drawn: it is CC-BY 4.0, already
# a consistent set, flat enough to read at 96px in both themes, and every file
# is under a kilobyte. Bundling it also means the pictures look the same on
# every platform, which platform emoji fonts do not.
#
#   ruby tool/fetch_vocab_art.rb          # only what is missing
#   ruby tool/fetch_vocab_art.rb --force  # re-download everything

