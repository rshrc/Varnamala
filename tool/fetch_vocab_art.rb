# Concepts whose picture is built from several glyphs instead of being one.
#
# A single carrot is a carrot, not "vegetable". The tile only reads as the
# category when it shows a small pile, so this one is assembled from three
# Twemoji sources, each scaled and placed inside one 36x36 viewBox.
#
# [codepoint, scale, dx, dy] - drawn back to front.
COMPOSED = {
  'vegetable' => [
    ['1f966', 0.62, -1.5, 1.0],  # broccoli, back left
    ['1f345', 0.52, 17.0, 2.0],  # tomato, back right
    ['1f955', 0.70, 6.0, 13.0]   # carrot, front centre
  ]
}.freeze

