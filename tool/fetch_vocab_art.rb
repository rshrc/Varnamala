def svg_body(source)
  source.sub(/\A.*?<svg[^>]*>/m, '').sub(%r{</svg>\s*\z}m, '').strip
end

def compose(parts)
  layers = parts.map do |codepoint, scale, dx, dy|
    body = fetch(codepoint)
    raise "could not fetch #{codepoint}" if body.nil?

    "  <g transform=\"translate(#{dx} #{dy}) scale(#{scale})\">\n" \
      "#{svg_body(body)}\n  </g>"
  end
  "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 36 36\">\n" \
    "#{layers.join("\n")}\n</svg>\n"
end

def fetch(codepoint)
  uri = URI("#{BASE}/#{codepoint}.svg")
  response = Net::HTTP.get_response(uri)
  return response.body if response.is_a?(Net::HTTPSuccess)

  warn "  #{codepoint}: HTTP #{response.code}"
  nil
end

def main
  force = ARGV.include?('--force')

  concepts = JSON.parse(CONCEPTS.read)['concepts'].map { |concept| concept['id'] }
  missing_codepoint = concepts - CODEPOINTS.keys - COMPOSED.keys
  orphaned = (CODEPOINTS.keys + COMPOSED.keys) - concepts
  unless missing_codepoint.empty?
    abort "No codepoint for: #{missing_codepoint.join(', ')}"
  end
  warn "Codepoints with no concept: #{orphaned.join(', ')}" unless orphaned.empty?

  OUT_DIR.mkpath
  (OUT_DIR / 'LICENSE').write(LICENSE)

  downloaded = 0
  skipped = 0
  failed = []

  concepts.each do |id|
    target = OUT_DIR / "#{id}.svg"
    if target.exist? && !force
      skipped += 1
      next
    end

    body =
      if COMPOSED.key?(id)
        begin
          compose(COMPOSED.fetch(id))
        rescue RuntimeError
          nil
        end
      else
        fetch(CODEPOINTS.fetch(id))
      end

    if body.nil?
      failed << id
      next
    end

    target.write(body)
    downloaded += 1
  end

  puts "#{downloaded} downloaded, #{skipped} already present, #{failed.size} failed"
  abort "Failed: #{failed.join(', ')}" unless failed.empty?
end

main if $PROGRAM_NAME == __FILE__
